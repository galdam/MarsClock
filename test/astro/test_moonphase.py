
import pytest
from marsclock.astro import moonphase, astrotime

# https://www.timeanddate.com/moon/phases/?year=2024

@pytest.mark.parametrize("year,month,mday", [
    [1990, 11, 17],
    [2000, 1, 6], [2000, 2, 5], [2000, 3, 6], [2000, 4, 4],
    [2000, 5, 4], [2000, 6, 2], [2000, 7, 1], [2000, 7, 31], [2000, 8, 29],
    [2000, 9, 27], [2000, 10, 27], [2000, 11, 25], [2000, 12, 25],

    [2024, 1, 11], [2024, 2, 9], [2024, 3, 10], [2024, 4, 8],
    [2024, 5, 8],  [2024, 6, 6], [2024, 7, 5],  [2024, 8, 4],
    [2024, 9, 3], [2024, 10, 2], [2024, 11, 1],[2024, 12, 1],

    [2044, 1, 30], [2044, 2, 28], [2044, 3, 29], [2044, 4, 27],
    [2044, 5, 27], [2044, 6, 25], [2044, 7, 24], [2044, 8, 23],
    [2044, 9, 21], [2044, 10, 21], [2044, 11, 19], [2044, 12, 19],

    #[2090, 1, 30], [2100, 1, 12], [2100, 2, 11], [2100, 3, 10]
])
def test_new_moons(year, month, mday):
    days = astrotime.EarthDateTime(year, month, mday, 0, 0, 0).epoch_tc_days
    result = moonphase.MoonPhase.moon_phase_pct(days)
    assert 0.95 < result <= 1 or 0 <= result < 0.05, result

@pytest.mark.parametrize("year,month,mday", [
    [2000, 1, 21], [2000, 2, 19], [2000, 3, 20], [2000, 4, 18],
    [2000, 5, 18], [2000, 6, 16], [2000, 7, 16], [2000, 8, 15],
    [2000, 9, 13], [2000, 10, 13], [2000, 11, 11], [2000, 12, 11],

    [2024, 1, 25], [2024, 2, 24], [2024, 3, 25], [2024, 4, 24],
    [2024, 5, 23], [2024, 6, 22], [2024, 7, 21], [2024, 8, 19],
    [2024, 9, 18], [2024, 10, 17], [2024, 11, 15], [2024, 12, 15],

    [2044, 1, 14], [2044, 2, 13], [2044, 3, 13], [2044, 4, 12],
    [2044, 5, 12], [2044, 6, 10], [2044, 7, 10], [2044, 8, 8],
    [2044, 9, 7], [2044, 10, 7], [2044, 11, 5], [2044, 12, 4],
])
def test_full_moons(year, month, mday):
    days = astrotime.EarthDateTime(year, month, mday, 0, 0, 0).epoch_tc_days
    result = moonphase.MoonPhase.moon_phase_pct(days)
    assert 0.45 < result <= 0.55, result

