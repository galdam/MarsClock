import pytest
from marsclock.astro.astrotime import MarsDateTime


@pytest.mark.parametrize("year", [0, 2, 4, 6, 8, 12, 14, 16, 18, 202])
def test_non_leap_years(year):
    assert not MarsDateTime._is_leap_year(year)


@pytest.mark.parametrize("year", [1, 3, 5, 7, 9, 10, 11, 13, 15, 17, 19, 20, 21, 201])
def test_leap_years(year):
    assert MarsDateTime._is_leap_year(year)


